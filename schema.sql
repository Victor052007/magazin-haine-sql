-- Furnizorii magazinului
CREATE TABLE furnizori (
    id      INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_f   INTEGER       NOT NULL UNIQUE,          -- codul furnizorului
    nume    VARCHAR(100)  NOT NULL,
    adresa  VARCHAR(200)
);

-- Produsele aflate in stoc
CREATE TABLE stocuri (
    id          INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codp        VARCHAR(20)   NOT NULL UNIQUE,      -- codul produsului
    denumire    VARCHAR(100)  NOT NULL,
    cantitate   INTEGER       NOT NULL CHECK (cantitate >= 0),  -- cantitatea din stoc
    cant_norm   INTEGER       NOT NULL CHECK (cant_norm >= 0),  -- stocul minim normal
    unit_mas    VARCHAR(10)   NOT NULL,             -- unitatea de masura (buc, pck)
    pret        NUMERIC(10,2) NOT NULL CHECK (pret > 0),        -- pret unitar (RON)
    data_achiz  DATE          NOT NULL,             -- data achizitiei
    cond_spec   NUMERIC(1)    DEFAULT 0 NOT NULL CHECK (cond_spec IN (0, 1)),  -- 1 = necesita conditii speciale de depozitare
    codf        INTEGER       NOT NULL,             -- furnizorul produsului
    CONSTRAINT fk_stocuri_furnizori FOREIGN KEY (codf) REFERENCES furnizori (cod_f)
);

CREATE INDEX idx_stocuri_codf ON stocuri (codf);
